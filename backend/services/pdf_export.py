_REFS_HEADING_RE = re.compile(r"^\s*(references|sources|kaynaklar)\s*:?\s*$", re.IGNORECASE)
_MD_HEADING_RE = re.compile(r"^#{1,6}\s+")
_MD_BOLD_RE = re.compile(r"\*\*(.+?)\*\*")
_MD_ITALIC_RE = re.compile(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)")
_MD_INLINE_CODE_RE = re.compile(r"`([^`]+)`")
_MD_LINK_RE = re.compile(r"\[([^\]]+)\]\([^)]+\)")
_MD_HR_RE = re.compile(r"^[-*_]{3,}\s*$")
_MD_LIST_RE = re.compile(r"^[-*•]\s+")
_MD_NUM_LIST_RE = re.compile(r"^\d+\.\s+")
_PIPE_ONLY_RE = re.compile(r"^[-:\s|]+$")

_XHTML2PDF_FONTS_REGISTERED = False


def _ensure_unicode_str(value: Any) -> str:
    """Normalize renderer inputs to a proper Unicode str (never raw bytes)."""
    if value is None:
        return ""
    if isinstance(value, bytes):
        return value.decode("utf-8")
    return str(value)


@lru_cache(maxsize=2)
def _decode_embedded_font(zlib_b64: str) -> bytes:
    return zlib.decompress(base64.b64decode(zlib_b64.encode("ascii")))


@lru_cache(maxsize=1)
def _embedded_font_files() -> tuple[str, str]:
    """Materialize embedded TTF bytes to temp files (needed by xhtml2pdf/reportlab)."""
    tmp = Path(tempfile.gettempdir()) / "vectorvault_pdf_fonts"
    tmp.mkdir(parents=True, exist_ok=True)
    regular = tmp / "DejaVuSansEmbed.ttf"
    bold = tmp / "DejaVuSansEmbed-Bold.ttf"
    if not regular.exists() or regular.stat().st_size == 0:
        regular.write_bytes(_decode_embedded_font(_DEJAVU_SANS_ZLIB_B64))
    if not bold.exists() or bold.stat().st_size == 0:
        bold.write_bytes(_decode_embedded_font(_DEJAVU_SANS_BOLD_ZLIB_B64))
    return str(regular), str(bold)


def _font_face_css(renderer: Literal["weasyprint", "xhtml2pdf"]) -> str:
    """CDN-free @font-face rules backed by the embedded Base64 font payload."""
    # xhtml2pdf on Windows fails when materializing data-URI fonts via
    # NamedTemporaryFile (file lock). It uses ReportLab registration instead.
    if renderer != "weasyprint":
        return ""

    reg_b64 = base64.b64encode(_decode_embedded_font(_DEJAVU_SANS_ZLIB_B64)).decode("ascii")
    bold_b64 = base64.b64encode(_decode_embedded_font(_DEJAVU_SANS_BOLD_ZLIB_B64)).decode(
        "ascii"
    )
    return f"""
@font-face {{
  font-family: {_EMBEDDED_FONT_FAMILY};
  src: url("data:font/truetype;base64,{reg_b64}") format("truetype");
  font-weight: normal;
  font-style: normal;
}}
@font-face {{
  font-family: {_EMBEDDED_FONT_FAMILY};
  src: url("data:font/truetype;base64,{bold_b64}") format("truetype");
  font-weight: bold;
  font-style: normal;
}}
"""


def _register_xhtml2pdf_fonts() -> None:
    """Register embedded DejaVu fonts for xhtml2pdf Unicode output.

    Font bytes come from the Base64 payload in this module (no external/CDN
    font file). ReportLab registration + DEFAULT_FONT aliases let xhtml2pdf
    resolve the family without @font-face temp-file materialization.
    """
    global _XHTML2PDF_FONTS_REGISTERED
    if _XHTML2PDF_FONTS_REGISTERED:
        return
    from reportlab.lib.fonts import addMapping  # type: ignore[import-untyped]
    from reportlab.pdfbase import pdfmetrics  # type: ignore[import-untyped]
    from reportlab.pdfbase.ttfonts import TTFont  # type: ignore[import-untyped]
    from xhtml2pdf import default as xhtml2pdf_default  # type: ignore[import-untyped]

    regular_path, bold_path = _embedded_font_files()
    names = set(pdfmetrics.getRegisteredFontNames())
    bold_name = f"{_EMBEDDED_FONT_FAMILY}-Bold"
    if _EMBEDDED_FONT_FAMILY not in names:
        pdfmetrics.registerFont(TTFont(_EMBEDDED_FONT_FAMILY, regular_path))
    if bold_name not in names:
        pdfmetrics.registerFont(TTFont(bold_name, bold_path))

    # ReportLab family + style mappings used by xhtml2pdf tt2ps().
    pdfmetrics.registerFontFamily(
        _EMBEDDED_FONT_FAMILY,
        normal=_EMBEDDED_FONT_FAMILY,
        bold=bold_name,
    )
    addMapping(_EMBEDDED_FONT_FAMILY, 0, 0, _EMBEDDED_FONT_FAMILY)
    addMapping(_EMBEDDED_FONT_FAMILY, 1, 0, bold_name)
    addMapping(_EMBEDDED_FONT_FAMILY, 0, 1, _EMBEDDED_FONT_FAMILY)
    addMapping(_EMBEDDED_FONT_FAMILY, 1, 1, bold_name)

    # xhtml2pdf resolves CSS font-family via this lowercase map.
    family_key = _EMBEDDED_FONT_FAMILY.lower()
    xhtml2pdf_default.DEFAULT_FONT[family_key] = _EMBEDDED_FONT_FAMILY
    xhtml2pdf_default.DEFAULT_FONT[f"{family_key}-bold"] = bold_name
    # Prefer Unicode-capable face over Helvetica for generic/default families.
    for alias in ("helvetica", "sans-serif", "sansserif", "sans", "arial"):
        xhtml2pdf_default.DEFAULT_FONT[alias] = _EMBEDDED_FONT_FAMILY
    for alias in ("helvetica-bold", "arial-bold"):
        xhtml2pdf_default.DEFAULT_FONT[alias] = bold_name

    _XHTML2PDF_FONTS_REGISTERED = True


def _strip_references_section(text: str) -> str:
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if _REFS_HEADING_RE.match(line.strip()):
            return "\n".join(lines[:i]).rstrip()
    return text.rstrip()


def _escape(text: str) -> str:
    return html.escape(_ensure_unicode_str(text), quote=True)


def _strip_markdown_inline(text: str) -> str:
    """Remove raw markdown markers while keeping readable plain text."""
    text = _ensure_unicode_str(text)
    text = _MD_LINK_RE.sub(r"\1", text)
    text = _MD_BOLD_RE.sub(r"\1", text)
    text = _MD_ITALIC_RE.sub(r"\1", text)
    text = _MD_INLINE_CODE_RE.sub(r"\1", text)
    # Leftover emphasis / pipe / strike markers that are not structural.
    text = text.replace("**", "").replace("__", "").replace("~~", "")
    text = text.replace("*", "").replace("|", "")
    return text.strip()


def _strip_markdown_line(line: str) -> str:
    stripped = _ensure_unicode_str(line).strip()
    if not stripped:
        return ""
    if _MD_HR_RE.match(stripped):
        return ""
    stripped = _MD_HEADING_RE.sub("", stripped)
    stripped = _MD_LIST_RE.sub("", stripped)
    stripped = _MD_NUM_LIST_RE.sub("", stripped)
    return _strip_markdown_inline(stripped)


def _table_row_to_labeled_block(header: list[str], row: list[str]) -> str:
    """Turn one markdown-table body row into labeled text lines."""
    parts: list[str] = []
    for i, cell in enumerate(row):
        label = header[i].strip() if i < len(header) else f"Field {i + 1}"
        value = cell.strip()
        if not value or _PIPE_ONLY_RE.match(value):
            continue
        label = _strip_markdown_inline(label)
        value = _strip_markdown_inline(value)
        if label:
            parts.append(
                f'<p class="labeled-line">'
                f'<span class="label">{_escape(label)}:</span> {_escape(value)}'
                f"</p>"
            )
        else:
            parts.append(f'<p class="analysis-p">{_escape(value)}</p>')
    if not parts:
        return ""
    return f'<div class="labeled-block">{"".join(parts)}</div>'


def _format_analysis_html(analysis: str) -> str:
    """Convert analysis text into plain HTML blocks (no tables, no raw markdown)."""
    text = _strip_references_section(_ensure_unicode_str(analysis))
    if not text.strip():
        return '<p class="muted">No analysis content provided.</p>'

    blocks: list[str] = []
    paragraph: list[str] = []
    table_rows: list[list[str]] = []
    list_items: list[str] = []
    in_list = False

    def flush_paragraph() -> None:
        nonlocal paragraph
        if paragraph:
            body = "<br/>".join(_escape(line) for line in paragraph)
            blocks.append(f'<p class="analysis-p">{body}</p>')
            paragraph = []

    def flush_list() -> None:
        nonlocal list_items, in_list
        if list_items:
            items = "".join(f"<li>{_escape(item)}</li>" for item in list_items)
            blocks.append(f'<ol class="analysis-list">{items}</ol>')
            list_items = []
        in_list = False

    def flush_table() -> None:
        nonlocal table_rows
        if not table_rows:
            return
        header = [_strip_markdown_inline(c) for c in table_rows[0]]
        for row in table_rows[1:]:
            if all(_PIPE_ONLY_RE.match(cell.strip()) for cell in row):
                continue
            block = _table_row_to_labeled_block(header, row)
            if block:
                blocks.append(block)
        table_rows = []

    for raw_line in text.split("\n"):
        line = raw_line.rstrip()
        stripped = line.strip()

        # Markdown pipe tables → labeled text blocks (never HTML <table>).
        if stripped.startswith("|") and stripped.count("|") >= 2:
            flush_paragraph()
            flush_list()
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            table_rows.append(cells)
            continue

        if table_rows:
            flush_table()

        if _MD_HEADING_RE.match(stripped):
            flush_paragraph()
            flush_list()
            heading = _strip_markdown_line(stripped)
            if heading:
                blocks.append(f'<h3 class="analysis-h3">{_escape(heading)}</h3>')
            continue

        if _MD_LIST_RE.match(stripped) or _MD_NUM_LIST_RE.match(stripped):
            flush_paragraph()
            in_list = True
            item = _strip_markdown_line(stripped)
            if item:
                list_items.append(item)
            continue

        if in_list and not stripped:
            flush_list()
            continue

        if in_list and stripped:
            flush_list()

        if not stripped or _MD_HR_RE.match(stripped):
            flush_paragraph()
            continue

        cleaned = _strip_markdown_line(stripped)
        if cleaned:
            paragraph.append(cleaned)

    flush_paragraph()
    flush_list()
    flush_table()
    return "\n".join(blocks)


def _build_sources_html(sources: list[dict[str, Any]]) -> str:
    """Numbered evidence list — no tables."""
    if not sources:
        return '<p class="muted">No retrieved evidence sources recorded for this analysis.</p>'

    items: list[str] = []
    for i, src in enumerate(sources, start=1):
        filename = _strip_markdown_inline(str(src.get("filename", "Unknown")))
        confidence = src.get("confidence")
        chunk_index = src.get("chunk_index")
        conf_label = f"{confidence:.1f}%" if isinstance(confidence, (int, float)) else "N/A"
        chunk_label = str(chunk_index) if chunk_index is not None else "N/A"
        line = (
            f"{i}. [{filename}] — Chunk {chunk_label} — Confidence: {conf_label}"
        )
        items.append(f'<p class="source-item">{_escape(line)}</p>')

    return f'<div class="sources-list">{"".join(items)}</div>'


